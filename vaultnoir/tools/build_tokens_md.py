"""TOKENS.md from tokens.json (run after build_tokens.py).

    python tools/build_tokens_md.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
USE = {
    "bg": "page", "surface": "cards, fields, panels", "surface-2": "buttons, menus", "surface-3": "hover, selected, chips on",
    "line": "borders", "line-2": "strong borders, control outlines", "text": "body text", "muted": "secondary text",
    "faint": "hints, icons (3:1, not text)", "focus": "focus ring", "scrim": "modal backdrop", "shadow": "menus, toasts",
    "media": "behind pictures and video", "media-scrim": "tags over pictures", "on-media": "text over pictures",
}


def main() -> None:
    d = json.loads((ROOT / "tokens.json").read_text(encoding="utf-8"))
    out = ["# vaultnoir tokens", "",
           "Generated by `tools/build_tokens.py` into `tokens.css` and `tokens.json` (this file: `tools/build_tokens_md.py`);",
           "change the inputs there, never the CSS.",
           "Set `data-theme=\"dark|light\"` and `data-accent=\"red|sky|violet|pink|amber\"` on `<html>`; unset means dark + red.", "",
           "Rules: text >= 4.5:1 and UI marks / focus ring >= 3:1, measured on `surface-3` (the worst surface they sit on).",
           "Signal colours and accent text are also checked on their own tints (badges, alerts, the Ask bar when on).",
           "`faint` is for hints, icons and disabled controls only (3:1), never for text someone must read.", ""]
    for mode in ("dark", "light"):
        t = d["tokens"][mode]
        out += [f"## {mode.title()}", "", "| Token | Value | Use |", "|---|---|---|"]
        for k, v in t["neutrals"].items():
            out.append(f"| `--vwnr-{k}` | `{v}` | {USE.get(k, '')} |")
        for k, v in t["signals"].items():
            use = "signal background" if k.endswith("soft") else "signal (always with a word or icon)"
            out.append(f"| `--vwnr-{k}` | `{v}` | {use} |")
        out += ["", "| Accent | mark (`--vwnr-accent`) | text (`-text`) | fill / label (`-fill` / `-on`) | ramp 1..5 |",
                "|---|---|---|---|---|"]
        for name, a in t["accents"].items():
            ramp = " ".join(f"`{a[f'ramp-{i}']}`" for i in range(1, 6))
            out.append(f"| {name} | `{a['accent']}` | `{a['accent-text']}` | `{a['accent-fill']}` / `{a['accent-on']}` | {ramp} |")
        out += ["", "Categorical (`--vwnr-cat-1..5`): " + ", ".join(f"`{c}`" for c in t["categorical"]), ""]
    out += ["## Contrast (computed)", "", "| Mode | What | Ratio |", "|---|---|---|"]
    for r in d["contrast"]:
        if "accent" in r:
            out.append(f"| {r['mode']} | {r['accent']}: mark / text on surface-3, label on fill | "
                       f"{r['mark_on_surface3']} / {r['text_on_surface3']} / {r['label_on_fill']} |")
        elif "neutral" in r:
            out.append(f"| {r['mode']} | {r['neutral']} | {r.get('on_surface3', r.get('on_surface'))} |")
        else:
            out.append(f"| {r['mode']} | {r['signal']} `{r['value']}` on surface-3 / on its own tint | "
                       f"{r['on_surface3']} / {r['on_own_tint']} |")
    out += ["", "## Geometry, type, motion (`vaultnoir.css`)", "", "| Group | Tokens |", "|---|---|",
            "| Type | `--vwnr-font-ui` Inter Tight, `--vwnr-font-mono` JetBrains Mono; sizes xs 11, sm 12, md 14 (body), lg 17, xl 20, 2xl 24, 3xl 29 (scale 1.2); leading 1.45 / 1.2 |",
            "| Space | 4, 8, 12, 16, 20, 24, 32 (`--vwnr-space-1..8`) |",
            "| Radius | xs 4, sm 7, default 8 (buttons, chips), md 9 (inputs), lg 10, xl 12 (cards), pill |",
            "| Sizes | top bar 56, control 34 (sm 28), input 38, chip 30, row 36, card min 200 (slider 180-220), gap 12, click floor 32 |",
            "| Motion | fast 120 ms, base 150 ms, ease `cubic-bezier(0.2, 0, 0, 1)`; 0 under reduced motion; no page transitions |",
            "| Layers | bar 40, menu 70, modal 80, toast 90 |", ""]
    (ROOT / "TOKENS.md").write_text("\n".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
